// ─────────────────────────────────────────────────────────────────────────────
// App-chrome translations.
//
// Scope, deliberately: this covers the SURROUNDING UI — menus, toolbar, tabs,
// panel headers, tooltips, status text — not the Blockly block labels
// themselves ("LED", "is Dark?", ...). Translating ~150 custom block strings
// correctly across ten languages, without a native speaker per language to
// check domain vocabulary ("potentiometer", "duty cycle"), is real
// mistranslation risk; the block layer stays English for now so a wrong
// translation never ends up misleading a student about what a block does.
//
// Add a language: add its code to LANGUAGES below and a matching entry here.
// Every key must exist in every language — English is the fallback if one
// is ever missing at runtime.
// ─────────────────────────────────────────────────────────────────────────────

export type LanguageCode = 'en' | 'es' | 'fr' | 'de' | 'hi' | 'zh' | 'ar' | 'pt' | 'ru' | 'ja'

export interface LanguageInfo {
  code: LanguageCode
  /** Shown in its own language, in the picker — not translated into the others. */
  nativeName: string
  rtl?: boolean
}

